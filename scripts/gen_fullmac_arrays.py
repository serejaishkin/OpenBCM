#!/usr/bin/env python3
"""Embed FullMAC firmware (*.bin) and board nvram (*.txt) into the kext.

usage: gen_fullmac_arrays.py [--if-changed] [--only stem[,stem...]] [dir] [out.cpp]
  dir      default: firmware/fullmac  (every *.bin = firmware, every *.txt = nvram)
  --only   embed just these stems (keeps the kext small); e.g. --only brcmfmac43602-pcie
Selection at runtime: auto by chip/rev, or OpenCore DeviceProperties
openbcm-fw / openbcm-nvram (stem names). See docs/FULLMAC_PLAN.md."""
import re, sys, os, glob
args = sys.argv[1:]
only = None
if_changed = False
if args and args[0] == "--if-changed":
    if_changed = True; args = args[1:]
if args and args[0] == "--only":
    only = set(args[1].split(",")); args = args[2:]
here = os.path.dirname(os.path.abspath(__file__))
d = args[0] if args else os.path.join(here, "..", "firmware", "fullmac")
out = args[1] if len(args) > 1 else os.path.join(here, "..", "itlwm", "hal_bcm", "FullmacFwArrays.cpp")

if os.environ.get("OPENBCM_FW_DIR") and not args:
    d = os.environ["OPENBCM_FW_DIR"]
if os.environ.get("OPENBCM_FW_ONLY") and only is None:
    only = set(os.environ["OPENBCM_FW_ONLY"].split(","))
import hashlib
def inputs_hash():
    h = hashlib.sha1()
    for ext in ("bin", "txt", "clm_blob"):
        for p in sorted(glob.glob(os.path.join(d, "*." + ext))):
            stem = os.path.basename(p)[:-(len(ext) + 1)]
            if only is None or stem in only:
                h.update(stem.encode()); h.update(open(p, "rb").read())
    return h.hexdigest()
stamp = "// INPUT-HASH: " + inputs_hash()
if if_changed and os.path.exists(out) and stamp in open(out).read():
    print("FullMAC firmware arrays up to date"); sys.exit(0)

def ident(s):
    return "".join(c if c.isalnum() else "_" for c in s)

def collect(ext):
    items = []
    for p in sorted(glob.glob(os.path.join(d, "*." + ext))):
        stem = os.path.basename(p)[:-(len(ext) + 1)]
        if only is None or stem in only:
            data = open(p, "rb").read()
            if ext == "txt":
                # Linux-style placeholder (xx:xx:..) is not a valid MAC; the real one is set by the driver later.
                data = re.sub(rb"(?m)^macaddr=[xX0-9a-fA-F:]*xx[xX0-9a-fA-F:]*", b"macaddr=00:90:4c:c5:12:38", data)
            items.append((stem, data))
    return items

def arr(name, data):
    rows = ["    " + ",".join("0x%02x" % b for b in data[i:i+16]) + "," for i in range(0, len(data), 16)]
    return "static const UInt8 %s[] = {\n%s\n};\n" % (name, "\n".join(rows) if rows else "    0")

fws, nvs, clms = collect("bin"), collect("txt"), collect("clm_blob")
with open(out, "w") as f:
    f.write(stamp + '\n// GENERATED by scripts/gen_fullmac_arrays.py — do not edit.\n#include <string.h>\n#include "FullmacFirmware.hpp"\n')
    for kind, items in (("fw", fws), ("nv", nvs), ("clm", clms)):
        for stem, data in items:
            f.write("// %s (%d bytes)\n" % (stem, len(data)))
            f.write(arr("%s_%s" % (kind, ident(stem)), data))
        f.write("static const FullmacBlob k_%s[] = {\n" % kind)
        for stem, data in items:
            f.write('    {"%s", %s_%s, %d},\n' % (stem, kind, ident(stem), len(data)))
        f.write("    {nullptr, nullptr, 0}\n};\n")
    f.write('''static const FullmacBlob *find(const FullmacBlob *t, const char *stem) {
    for (; t->stem; t++) if (strcmp(t->stem, stem) == 0) return t;
    return nullptr;
}
const FullmacBlob *bcmc_fullmac_find_fw(const char *stem) { return find(k_fw, stem); }
const FullmacBlob *bcmc_fullmac_find_nvram(const char *stem) { return find(k_nv, stem); }
const FullmacBlob *bcmc_fullmac_find_clm(const char *stem) { return find(k_clm, stem); }
''')
print("wrote %s: %d firmware, %d nvram, %d clm" % (out, len(fws), len(nvs), len(clms)))
